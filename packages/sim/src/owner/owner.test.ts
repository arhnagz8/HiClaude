const find = (ds: PolicyDecision[], type: string) => ds.filter((d) => d.decision.type === type)
/** run the policy for n days with obs generated by fn(day) and collect decisions by day */
const run = (p: OwnerPolicy, days: number, fn: (d: number) => ReturnType<typeof makeObs>) => {
  const all: Array<{ day: number; d: PolicyDecision }> = []
  for (let day = 0; day < days; day++) for (const d of p.decide(fn(day))) all.push({ day, d })
  return all
}

