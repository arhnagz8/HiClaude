describe('DecisionSchedule', () => {
  const file = [
    { date: '2026-10-05', type: 'set_target_coverage', days: 7 },
    { date: '2026-10-10', type: 'set_margin', family: 'gift_card', marginPct: 0.1 },
    { date: '2026-10-10', type: 'owner_draw', irt: 5_000_000 },
  ]
  it('releases each decision once at its IRST date', () => {
    const s = DecisionSchedule.fromFile(file)
    expect(s.popDue(fromIrst(2026, 10, 4, 23, 59))).toHaveLength(0)
    expect(s.popDue(fromIrst(2026, 10, 5, 0, 0))).toHaveLength(1)
    expect(s.popDue(fromIrst(2026, 10, 7))).toHaveLength(0)
    expect(s.popDue(fromIrst(2026, 10, 20)).map((d) => d.type)).toEqual(['set_margin', 'owner_draw'])
    expect(s.popDue(fromIrst(2026, 12, 1))).toHaveLength(0)
    expect(s.pending).toBe(0)
  })
  it('nextAt and size', () => {
    const s = DecisionSchedule.fromFile(file)
    expect(s.size).toBe(3)
    expect(s.nextAt()).toBe(fromIrst(2026, 10, 5))
  })
  it('applyDecisionsFile helper is idempotent through the applied set', () => {
    const applied = new Set<number>()
    expect(applyDecisionsFile(file, fromIrst(2026, 10, 6), applied)).toHaveLength(1)
    expect(applyDecisionsFile(file, fromIrst(2026, 10, 6), applied)).toHaveLength(0)
    expect(applyDecisionsFile(file, fromIrst(2026, 10, 11), applied)).toHaveLength(2)
  })
  it('catch-up: a late call releases everything that is overdue, in order', () => {
    const s = DecisionSchedule.fromFile(file)
    expect(s.popDue(fromIrst(2027, 1, 1)).map((d) => d.date)).toEqual(['2026-10-05', '2026-10-10', '2026-10-10'])
  })
  it('merge: file decisions win on the same lever; policy decisions on other levers survive', () => {
    const pol: PolicyDecision[] = [
      { decision: { type: 'set_margin', family: 'gift_card', marginPct: 0.11 }, rule: 'r', rationale: '', kpiSeen: {} },
      { decision: { type: 'set_margin', family: 'cloud', marginPct: 0.11 }, rule: 'r', rationale: '', kpiSeen: {} },
    ]
    const f = parseDecisionsFile([{ date: '2026-10-10', type: 'set_margin', family: 'gift_card', marginPct: 0.2 }])
    const m = mergeDecisionStreams(pol, f)
    expect(m.suppressed).toHaveLength(1)
    expect(m.merged.map((x) => x.source)).toEqual(['file', 'policy'])
    expect((m.merged[0]!.decision as { marginPct: number }).marginPct).toBe(0.2)
  })
  it('policy stays away from levers the file touched (observeExternal lock)', () => {
    const p = new OwnerPolicy({ preset: 'baseline' })
    p.observeExternal({ type: 'set_margin', family: 'gift_card', marginPct: 0.2 }, fromIrst(2026, 10, 3), 30)
    const out = run(p, 20, (d) => makeObs(d, { families: { gift_card: { orders: 10, quotes: 400, conversionRate: 0.6, marginPct: 0.2 } } }))
    expect(out.filter((x) => x.d.decision.type === 'set_margin')).toHaveLength(0)
  })
})

